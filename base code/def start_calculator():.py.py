def start_calculator():
    print("=== БАЗОВЫЙ КАЛЬКУЛЯТОР v1.0 ===")
    print("Введите 'q' или 'выход' в любой момент, чтобы закрыть программу.")
    print("-" * 32)

    # Бесконечный цикл, чтобы калькулятор работал, пока мы сами его не выключим
    while True:
        try:
            # 1. Получаем первое число (и сразу проверяем на команду выхода)
            num1_input = input("\nВведите первое число: ")
            if num1_input.lower() in ['q', 'выход']:
                print("Выключение терминала...")
                break
            
            # Превращаем текст в число с плавающей точкой (чтобы можно было вводить дробные)
            num1 = float(num1_input)

            # 2. Получаем математический оператор
            operator = input("Выберите операцию (+, -, *, /): ")
            if operator.lower() in ['q', 'выход']:
                break
                
            if operator not in ['+', '-', '*', '/']:
                print("Ошибка: Неизвестная операция. Попробуйте снова.")
                continue # Возвращает нас в начало цикла

            # 3. Получаем второе число
            num2_input = input("Введите второе число: ")
            if num2_input.lower() in ['q', 'выход']:
                break
            
            num2 = float(num2_input)

            # 4. Выполняем вычисление (Блок ветвления логики)
            if operator == '+':
                result = num1 + num2
            elif operator == '-':
                result = num1 - num2
            elif operator == '*':
                result = num1 * num2
            elif operator == '/':
                # Защита от деления на ноль - главного врага любого калькулятора
                if num2 == 0:
                    print("Критическая ошибка: Деление на ноль запрещено законами физики!")
                    continue
                result = num1 / num2

            # 5. Выводим результат
            # Если число целое (например, 5.0), убираем лишний ноль для красоты
            if result.is_integer():
                result = int(result)
                
            print(f">>> Результат: {num1} {operator} {num2} = {result}")

        # Обработка исключений: если пользователь ввел буквы вместо цифр
        except ValueError:
            print("Ошибка: Вы ввели текст или недопустимые символы. Нужны только цифры!")

# Запуск программы
if __name__ == "__main__":
    start_calculator()
    