#!/bin/bash

# Очистка экрана и скрытие курсора для красоты
clear
tput civvis

# Массив мистических символов Гастера
symbols=(
    "➔" "➘" "➙" "➚" "➛" "➜" "➞" "➟" "➠" "➡" "➢" "➣" "➤" "➥" "➦" "➧" "➨" "➩" "➪" 
    "➫" "➬" "➭" "➮" "➯" "➱" "➲" "➳" "➴" "➵" "➶" "➷" "➸" "🏹" "▲" "▼" "◀" "▶" "🞂" "🞄"
    "░" "▒" "▓" "█" "▄" "▀" "■" "□" "▪" "▫" "▬" "▲" "△" "▼" "▽" "◆" "◇" "○" "◎" "●"
    "◢" "◣" "◤" "◥" "☠" "☤" "☥" "☧" "☨" "☩" "☫" "☬" "☭" "☯" "☰" "☱" "☲" "☳" "☴" "☵"
    "☶" "☷" "☸" "☹" "☺" "☻" "☼" "☽" "☾" "☿" "♀" "♁" "♂" "♃" "♄" "♅" "♆" "♇" "♈" "♉"
    "♊" "♋" "♌" "♍" "♎" "♏" "♐" "♑" "♒" "♓" "♔" "♕" "♖" "♗" "♘" "♙" "♚" "♛" "♜" "♝"
    "♞" "♟" "♠" "♡" "♢" "♣" "♤" "♥" "♦" "♧" "♨" "♩" "♪" "♫" "♬" "♭" "♮" "♯" "♰" "♱"
)

# Функция для возврата курсора при выходе (Ctrl+C)
trap "tput cnorm; clear; exit" INT TERM EXIT

# Получаем размеры окна консоли
COLS=$(tput cols)
LINES=$(tput lines)

while true; do
    # 1. СЛУЧАЙНЫЙ СБОЙ: с шансом 5% курсор прыгает в случайное место экрана
    if [ $(( RANDOM % 100 )) -lt 5 ]; then
        rand_col=$(( RANDOM % COLS ))
        rand_line=$(( RANDOM % LINES ))
        tput cup $rand_line $rand_col
    fi

    # 2. ХАОТИЧНЫЙ ЦВЕТ: 90% времени цвет чисто оранжевый, 10% — "сбойные" цвета (красный, белый, темный)
    color_chance=$(( RANDOM % 100 ))
    if [ $color_chance -lt 85 ]; then
        COLOR='\033[38;5;208m' # Главный оранжевый
    elif [ $color_chance -lt 92 ]; then
        COLOR='\033[38;5;196m' # Вспышка красного
    elif [ $color_chance -lt 97 ]; then
        COLOR='\033[38;5;231m' # Вспышка белого
    else
        COLOR='\033[38;5;237m' # Темно-серый (эффект затухания)
    fi

    # 3. ХАОТИЧНЫЕОЕ ПЕРЕНЕСЕНИЕ: с шансом 3% принудительно переносим строку
    if [ $(( RANDOM % 100 )) -lt 3 ]; then
        echo ""
    fi

    # Выбираем случайный символ
    random_index=$(( RANDOM % ${#symbols[@]} ))
    
    # Выводим символ
    printf "${COLOR}%s\033[0m" "${symbols[$random_index]}"
    
    # 4. ХАОТИЧНАЯ СКОРОСТЬ: задержка постоянно меняется, создавая эффект "рывков"
    # Случайная задержка от 0.001 до 0.02 секунд
    sleep_time="0.0$(( (RANDOM % 2) + 1 ))"
    sleep $sleep_time
done
